"""Combine the js/ modules into one plain script: js/bundle.js.

Browsers refuse to load JavaScript modules from file:// (double-clicking
index.html), so index.html loads this single classic script instead. That
lets the app open straight from the folder as well as from a web host.

Run after editing anything in js/:
    py tools/build.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENTRY = 'js/app.js'
OUT = 'js/bundle.js'

IMPORT_RE = re.compile(r"""^\s*import\s+(?P<what>[\s\S]*?)\s+from\s+['"](?P<src>[^'"]+)['"]\s*;?""", re.M)
EXPORT_LIST_RE = re.compile(r"^\s*export\s*\{([^}]*)\}\s*;?\s*$", re.M)
EXPORT_DECL_RE = re.compile(r"^(\s*)export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)", re.M)
EXPORT_DEFAULT_RE = re.compile(r"^(\s*)export\s+default\s+", re.M)


def norm(base_file, src):
    path = os.path.normpath(os.path.join(os.path.dirname(base_file), src))
    return path.replace('\\', '/')


def transform(rel):
    with open(os.path.join(ROOT, rel), encoding='utf-8') as f:
        code = f.read()
    deps = []

    def repl_import(m):
        what, dep = m.group('what').strip(), norm(rel, m.group('src'))
        deps.append(dep)
        ref = f"__mods[{dep!r}]"
        if what.startswith('{'):
            names = [p.strip() for p in what.strip('{} \n').split(',') if p.strip()]
            parts = [f"{a.split(' as ')[0].strip()}: {a.split(' as ')[1].strip()}" if ' as ' in a else a for a in names]
            return f"const {{ {', '.join(parts)} }} = {ref};"
        return f"const {what} = {ref}.default;"

    code = IMPORT_RE.sub(repl_import, code)
    exported = []
    for m in EXPORT_LIST_RE.finditer(code):
        exported += [n.strip() for n in m.group(1).split(',') if n.strip()]
    code = EXPORT_LIST_RE.sub('', code)
    exported += [m.group(3) for m in EXPORT_DECL_RE.finditer(code)]
    code = EXPORT_DECL_RE.sub(lambda m: f"{m.group(1)}{m.group(2)} {m.group(3)}", code)
    code = EXPORT_DEFAULT_RE.sub(lambda m: f"{m.group(1)}__exp.default = ", code)
    if re.search(r"^\s*(import|export)\b", code, re.M):
        sys.exit(f"build: unsupported import/export left in {rel}")
    return code, deps, exported


def main():
    order, seen, mods = [], set(), {}

    def visit(rel, stack=()):
        if rel in seen:
            return
        if rel in stack:
            sys.exit('build: circular import ' + ' -> '.join(stack + (rel,)))
        code, deps, exported = transform(rel)
        mods[rel] = (code, exported)
        for d in deps:
            visit(d, stack + (rel,))
        seen.add(rel)
        order.append(rel)

    visit(ENTRY)
    out = ['// GENERATED by tools/build.py from the files in js/. Edit those, then rebuild.',
           '(function () {', "'use strict';", 'const __mods = {};']
    for rel in order:
        code, exported = mods[rel]
        out.append(f"\n// ---- {rel} ----")
        out.append(f"__mods[{rel!r}] = (function () {{\nconst __exp = {{}};")
        out.append(code.rstrip())
        if exported:
            out.append(f"Object.assign(__exp, {{ {', '.join(exported)} }});")
        out.append('return __exp;\n})();')
    out.append('})();\n')
    with open(os.path.join(ROOT, OUT), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print(f"built {OUT} from {len(order)} modules")


if __name__ == '__main__':
    main()
